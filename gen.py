_DIMS = {}
def img_dims(path):
    """Intrinsic (w, h) of a local /assets/... image, cached."""
    if path not in _DIMS:
        from PIL import Image
        with Image.open(os.path.join(os.path.dirname(__file__), path.lstrip("/"))) as im:
            _DIMS[path] = im.size
    return _DIMS[path]

